const norm = (s) => String(s || '').toLowerCase()
  .replace(/[\u064B-\u065F\u0640]/g, '').replace(/[أإآٱ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه')
  .replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)));
const STOP = new Set(['في', 'من', 'على', 'ايه', 'هو', 'هي', 'ده', 'دي', 'انا', 'عن', 'ان', 'لو', 'مع', 'او', 'يعني', 'ازاي', 'هل', 'ما', 'لا', 'مش', 'كان', 'عايز', 'عايزه', 'اللي', 'الى', 'الي']);
const stem = (w) => (w.length > 4 && w.startsWith('ال') ? w.slice(2) : w);
const tokens = (s) => norm(s).split(/[^a-z0-9\u0621-\u064A]+/).filter((w) => w.length > 1 && !STOP.has(w)).map(stem);

const INDEX = KB.map((e) => ({ e, set: new Set(tokens(e.k + ' ' + e.t)), kw: new Set(tokens(e.k)) }));

// Returns the best matching entries (score > 0 only). Empty array = out of scope.
function retrieve(question, n = 4) {
  const q = tokens(question);
  if (!q.length) return [];
  const scored = INDEX.map(({ e, set, kw }) => {
    let s = 0;
    for (const w of q) { if (kw.has(w)) s += 2; else if (set.has(w)) s += 1; }
    return { e, s };
  }).filter((x) => x.s >= 2).sort((a, b) => b.s - a.s).slice(0, n);
  return scored.map((x) => x.e);
}

